from typing import Optional
from pydantic import BaseModel, Field

class EvaluateRequest(BaseModel):
    generated_summary: str = Field(..., description="The summary generated by the ML system")
    reference_summary: str = Field(..., description="The gold-standard reference summary")

class RougeMetric(BaseModel):
    precision: float
    recall: float
    fmeasure: float

class EvaluateResponse(BaseModel):
    rouge1: RougeMetric
    rouge2: RougeMetric
    rougeL: RougeMetric
    original_length: int
    generated_length: int
    compression_ratio: float

class CompareEvaluateRequest(BaseModel):
    text: str = Field(..., description="Original input text to summarize and compare")
    reference_summary: str = Field(..., description="Gold-standard ground truth summary")
    max_length: Optional[int] = 150
    min_length: Optional[int] = 40

class CompareEvaluateResponse(BaseModel):
    base_t5_eval: Optional[EvaluateResponse] = None
    fine_tuned_t5_eval: Optional[EvaluateResponse] = None
    base_summary: str = ""
    fine_tuned_summary: str = ""
    fine_tuned_available: bool = False
